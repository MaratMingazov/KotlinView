package mingazov.kotlinview.instrumented

/**
 * Объект, за которым следит визуализатор: у него есть id и снимок состояния для событий.
 * Это контракт для тех, кто работает с объектом снаружи (реестр, сервисы).
 * EventSink сюда не входит: это внутренняя зависимость объекта — приходит через конструктор и наружу не торчит.
 */
interface Instrumented {
    val id: Long

    /** Состояние для событий: OBJECT_CREATED и state в каждом METHOD_*. */
    fun state(): Any?
}